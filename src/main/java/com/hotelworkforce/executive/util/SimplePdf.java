package com.hotelworkforce.executive.util;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

public final class SimplePdf {
    private SimplePdf() {}

    public static byte[] create(String title, List<String> lines) {
        List<List<String>> pages = paginate(title, lines, 45);
        int pageCount = pages.size();
        int objectCount = 3 + pageCount * 2;
        String[] objects = new String[objectCount + 1];

        objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
        StringBuilder kids = new StringBuilder("[");
        for (int i = 0; i < pageCount; i++) {
            int pageObj = 4 + i * 2;
            kids.append(pageObj).append(" 0 R ");
        }
        kids.append("]");
        objects[2] = "<< /Type /Pages /Kids " + kids + " /Count " + pageCount + " >>";
        objects[3] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";

        for (int i = 0; i < pageCount; i++) {
            int pageObj = 4 + i * 2;
            int contentObj = 5 + i * 2;
            String stream = contentStream(pages.get(i));
            objects[pageObj] = "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents " + contentObj + " 0 R >>";
            objects[contentObj] = "<< /Length " + stream.getBytes(StandardCharsets.ISO_8859_1).length + " >>\nstream\n" + stream + "\nendstream";
        }

        ByteArrayOutputStream out = new ByteArrayOutputStream();
        write(out, "%PDF-1.4\n%HotelWorkforce\n");
        int[] offsets = new int[objectCount + 1];
        for (int i = 1; i <= objectCount; i++) {
            offsets[i] = out.size();
            write(out, i + " 0 obj\n" + objects[i] + "\nendobj\n");
        }
        int xref = out.size();
        write(out, "xref\n0 " + (objectCount + 1) + "\n");
        write(out, "0000000000 65535 f \n");
        for (int i = 1; i <= objectCount; i++) write(out, String.format("%010d 00000 n \n", offsets[i]));
        write(out, "trailer\n<< /Size " + (objectCount + 1) + " /Root 1 0 R >>\nstartxref\n" + xref + "\n%%EOF");
        return out.toByteArray();
    }

    private static List<List<String>> paginate(String title, List<String> lines, int maxLines) {
        List<String> all = new ArrayList<>();
        all.add(title == null ? "Executive Report" : title);
        all.add("Generated by Hotel Workforce - Reporting & Executive Analytics");
        all.add("");
        all.addAll(lines);
        List<List<String>> pages = new ArrayList<>();
        for (int i = 0; i < all.size(); i += maxLines) pages.add(new ArrayList<>(all.subList(i, Math.min(i + maxLines, all.size()))));
        if (pages.isEmpty()) pages.add(List.of("Executive Report"));
        return pages;
    }

    private static String contentStream(List<String> lines) {
        StringBuilder sb = new StringBuilder("BT\n/F1 11 Tf\n50 795 Td\n16 TL\n");
        for (String line : lines) sb.append('(').append(pdfEscape(line)).append(") Tj\nT*\n");
        sb.append("ET");
        return sb.toString();
    }

    private static String pdfEscape(String input) {
        if (input == null) return "";
        String ascii = input.replaceAll("[^\\x20-\\x7E]", "?");
        return ascii.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)");
    }

    private static void write(ByteArrayOutputStream out, String value) {
        byte[] bytes = value.getBytes(StandardCharsets.ISO_8859_1);
        out.write(bytes, 0, bytes.length);
    }
}
